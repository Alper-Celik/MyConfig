#!/usr/bin/env python3
"""Regenerate decky-plugins.nix from decky-plugins.txt.

Plugins are resolved through the official Decky store registry, so the pins are
the exact artifacts the in-game store installs: a hash-addressed zip on the
store CDN, with the plugin directory name taken from the zip itself.

Usage: ./update-decky-plugins.py
"""

import base64
import io
import json
import os
import sys
import tempfile
import urllib.request
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = os.path.join(HERE, "decky-plugins.txt")
OUT = os.path.join(HERE, "decky-plugins.nix")

REGISTRY = "https://plugins.deckbrew.xyz/plugins"
CDN = "https://cdn.tzatzikiweeb.moe/file/steam-deck-homebrew/versions/{}.zip"

HEADER = "# Generated by ./update-decky-plugins.py; do not edit by hand."


def fail(message):
    sys.exit(f"error: {message}")


def fetch(url):
    request = urllib.request.Request(
        url,
        headers={
            "Accept": "application/json",
            "User-Agent": "update-decky-plugins",
        },
    )
    with urllib.request.urlopen(request) as response:
        return response.read()


def registry():
    data = json.loads(fetch(REGISTRY))
    if not isinstance(data, list):
        fail("store registry returned an unexpected payload")
    return {plugin["name"]: plugin for plugin in data}


def wanted():
    with open(SPEC, encoding="utf-8") as handle:
        for number, line in enumerate(handle, 1):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            yield number, line


def plugin_dir(archive, name):
    with zipfile.ZipFile(io.BytesIO(archive)) as zipped:
        top = {entry.split("/")[0] for entry in zipped.namelist()}
        if len(top) != 1:
            fail(f"{name}: zip does not have a single top-level directory ({sorted(top)})")
        directory = top.pop()
        if f"{directory}/plugin.json" not in zipped.namelist():
            fail(f"{name}: no {directory}/plugin.json in the zip")
        return directory


def nix_string(value):
    return value.replace("\\", "\\\\").replace('"', '\\"')


def main():
    store = registry()
    output = [HEADER, "{"]
    for number, name in wanted():
        plugin = store.get(name)
        if plugin is None:
            fail(f"{SPEC}:{number}: {name!r} is not in the Decky store")
        versions = plugin.get("versions") or []
        if not versions:
            fail(f"{name}: no published versions")
        version = versions[0]
        url = CDN.format(version["hash"])
        print(f"==> {name}: {version['name']}", file=sys.stderr)
        archive = fetch(url)
        directory = plugin_dir(archive, name)
        hash_ = "sha256-" + base64.b64encode(bytes.fromhex(version["hash"])).decode()
        output += [
            f'  "{nix_string(name)}" = {{',
            f'    dir = "{nix_string(directory)}";',
            f'    version = "{nix_string(version["name"])}";',
            f'    url = "{url}";',
            f'    hash = "{hash_}";',
            "  };",
        ]
    output.append("}")

    directory = os.path.dirname(OUT)
    with tempfile.NamedTemporaryFile(
        "w", dir=directory, delete=False, encoding="utf-8"
    ) as handle:
        handle.write("\n".join(output) + "\n")
        temporary = handle.name
    os.replace(temporary, OUT)
    print(f"wrote {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
